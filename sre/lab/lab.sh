#!/usr/bin/env bash
# Local kind lab for the SRE agent.
#   lab.sh up                 create cluster, metrics-server, shop app, read-only identity + MCP config
#   lab.sh break <scenario>   inject a failure (see list below)
#   lab.sh reset              restore the healthy baseline
#   lab.sh status             what's running
#   lab.sh down               delete the cluster
#   lab.sh remote-up          add Keycloak + an in-cluster MCP server over HTTP with OAuth; writes remote.env
#   lab.sh remote-forward     port-forward Keycloak (18080) and the MCP server (18081); keep it running
#   lab.sh remote-down        remove them
set -euo pipefail
cd "$(dirname "$0")"
LAB=$(pwd)
CLUSTER=sre-lab
CTX=kind-$CLUSTER
K="kubectl --context $CTX"
METRICS_SERVER=v0.9.1

scenarios() {
  cat <<'EOF'
  crashloop     checkout-api rollout with a bad flag -> new pod CrashLoopBackOff, rollout stuck (old pods still serve)
  bad-image     checkout-api image tag typo -> new pod ErrImagePull/ImagePullBackOff, rollout stuck
  oom           payments-worker loads 128MB under a 64Mi limit -> new pod OOMKilled, restarting
  pending       frontend requests 32 CPUs -> new pod Pending (Insufficient cpu), rollout stuck
  no-endpoints  checkout-api Service selector typo -> pods healthy, but traffic fails (loadgen 000s)
  errors        checkout-api random errors -> pods healthy, ~1/3 requests fail (loadgen 4xx/5xx)
  unready       frontend readiness never passes -> new pod Running 0/1 Ready, rollout stuck
EOF
}

add_arg() {  # deployment arg
  $K -n shop patch deploy "$1" --type=json -p "[{\"op\":\"add\",\"path\":\"/spec/template/spec/containers/0/args/-\",\"value\":\"$2\"}]"
}

case "${1:-}" in
  up)
    kind get clusters | grep -qx $CLUSTER || kind create cluster --name $CLUSTER --wait 120s
    $K apply -f "https://github.com/kubernetes-sigs/metrics-server/releases/download/$METRICS_SERVER/components.yaml"
    # kind kubelets use self-signed certs
    $K -n kube-system patch deploy metrics-server --type=json \
      -p '[{"op":"add","path":"/spec/template/spec/containers/0/args/-","value":"--kubelet-insecure-tls"}]' || true
    $K apply -f rbac.yaml
    # first apply creates the CRD; its SLO objects need it Established, so wait and apply again
    $K apply -f app.yaml || { $K wait --for condition=established --timeout=60s crd/servicelevelobjectives.sre.demo.io; $K apply -f app.yaml; }
    $K -n shop rollout status deploy --timeout=180s

    # Read-only kubeconfig for the MCP server (token valid 24h; re-run `lab.sh up` to refresh).
    server=$(kubectl config view --raw -o jsonpath="{.clusters[?(@.name==\"$CTX\")].cluster.server}")
    kubectl config view --raw -o jsonpath="{.clusters[?(@.name==\"$CTX\")].cluster.certificate-authority-data}" | base64 -d > ca.crt
    token=$($K -n sre-system create token sre-agent --duration=24h)
    rm -f readonly.kubeconfig
    KC="kubectl --kubeconfig readonly.kubeconfig"
    $KC config set-cluster $CLUSTER --server="$server" --certificate-authority=ca.crt --embed-certs=true >/dev/null
    $KC config set-credentials sre-agent --token="$token" >/dev/null
    $KC config set-context sre-agent --cluster=$CLUSTER --user=sre-agent --namespace=shop >/dev/null
    $KC config use-context sre-agent >/dev/null
    rm -f ca.crt; chmod 600 readonly.kubeconfig

    cat > mcp.toml <<EOF
# containers/kubernetes-mcp-server config (generated by lab.sh up)
kubeconfig = "$LAB/readonly.kubeconfig"
read_only = true              # only tools annotated readOnlyHint=true are registered
toolsets = ["core"]           # pods, generic resources (incl. CRDs), events, nodes, top
denied_resources = [{group = "", version = "v1", kind = "Secret"}]
log_file = "$LAB/mcp.log"
EOF
    echo; echo "Lab ready. Read-only identity check:"
    $KC auth can-i delete pods -n shop || true
    $KC auth can-i list servicelevelobjectives.sre.demo.io -n shop
    echo; echo "Scenarios:"; scenarios
    ;;
  break)
    case "${2:-}" in
      crashloop)    add_arg checkout-api --port=nine-eight-nine-eight ;;
      bad-image)    $K -n shop set image deploy/checkout-api app=ghcr.io/stefanprodan/podinfo:6.17.0-hotfix ;;
      oom)          add_arg payments-worker --stress-memory=128 ;;
      pending)      $K -n shop set resources deploy/frontend --requests=cpu=32 ;;
      no-endpoints) $K -n shop patch svc checkout-api -p '{"spec":{"selector":{"app":"checkout"}}}' ;;
      errors)       add_arg checkout-api --random-error ;;
      unready)      add_arg frontend --unready ;;
      *) echo "usage: lab.sh break <scenario>"; scenarios; exit 1 ;;
    esac
    echo "Injected '$2'. Give it ~30s to show symptoms, then ask the agent e.g. 'customers report checkout problems, investigate the shop namespace'."
    ;;
  reset)
    $K apply -f app.yaml >/dev/null
    $K -n shop rollout status deploy --timeout=180s
    ;;
  status)
    $K -n shop get deploy,pods,svc,endpointslices,slo -o wide
    ;;
  down)
    kind delete cluster --name $CLUSTER
    rm -rf readonly.kubeconfig mcp.toml mcp.log remote.env remote-pki
    ;;
  remote-up)
    # Issuer = the node IP + Keycloak NodePort: reachable from the API server (host network) and from pods.
    # ponytail: the node IP can change when Docker restarts; re-run remote-up then.
    node_ip=$(docker inspect $CLUSTER-control-plane --format '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}')
    issuer_base="https://$node_ip:30443"; issuer="$issuer_base/realms/sre"

    # 1. Lab CA + Keycloak serving cert (the API server only accepts https issuers)
    mkdir -p remote-pki
    if ! openssl x509 -in remote-pki/tls.crt -noout -checkip "$node_ip" 2>/dev/null | grep -q 'does match'; then
      (cd remote-pki && umask 077 &&
        openssl req -x509 -newkey rsa:2048 -nodes -days 30 -subj /CN=sre-lab-oidc-ca -keyout ca.key -out ca.crt \
          -addext basicConstraints=critical,CA:TRUE -addext keyUsage=critical,keyCertSign,cRLSign \
          -addext subjectKeyIdentifier=hash 2>/dev/null &&
        openssl req -newkey rsa:2048 -nodes -subj /CN=keycloak -keyout tls.key -out tls.csr 2>/dev/null &&
        printf 'subjectAltName=IP:%s,DNS:localhost\nbasicConstraints=CA:FALSE\nextendedKeyUsage=serverAuth\nauthorityKeyIdentifier=keyid\nsubjectKeyIdentifier=hash\n' "$node_ip" > ext.cnf &&
        openssl x509 -req -in tls.csr -CA ca.crt -CAkey ca.key -CAcreateserial -days 30 -extfile ext.cnf -out tls.crt 2>/dev/null &&
        rm -f ca.key tls.csr ext.cnf ca.srl)
    fi

    # 2. API server trusts Keycloak tokens for audience kubernetes-mcp-server; username = oidc:<preferred_username>
    node="docker exec -i $CLUSTER-control-plane"
    {
      printf 'apiVersion: apiserver.config.k8s.io/v1\nkind: AuthenticationConfiguration\njwt:\n- issuer:\n'
      printf '    url: %s\n    audiences: [kubernetes-mcp-server]\n    certificateAuthority: |\n' "$issuer"
      sed 's/^/      /' remote-pki/ca.crt
      printf '  claimMappings:\n    username: {claim: preferred_username, prefix: "oidc:"}\n'
    } | $node sh -c 'mkdir -p /etc/kubernetes/pki/oidc && cat > /etc/kubernetes/pki/oidc/auth-config.yaml'
    manifest=/etc/kubernetes/manifests/kube-apiserver.yaml
    if ! $node grep -q authentication-config $manifest; then
      # kubeadm already mounts /etc/kubernetes/pki into the API server; later file changes are picked up live
      $node sed -i '/- kube-apiserver$/a\    - --authentication-config=/etc/kubernetes/pki/oidc/auth-config.yaml' $manifest
      echo "Restarting kube-apiserver with --authentication-config ..."; sleep 20
      until $K get --raw /readyz >/dev/null 2>&1; do sleep 3; done
    fi

    # 3. Keycloak + MCP server
    $K create namespace keycloak --dry-run=client -o yaml | $K apply -f - >/dev/null
    if ! $K -n keycloak get secret clients >/dev/null 2>&1; then
      $K -n keycloak create secret generic clients --from-literal=admin-password="$(openssl rand -hex 16)" \
        --from-literal=sre-agent="$(openssl rand -hex 24)" --from-literal=other-app="$(openssl rand -hex 24)" >/dev/null
    fi
    $K -n keycloak create secret tls tls --cert=remote-pki/tls.crt --key=remote-pki/tls.key --dry-run=client -o yaml | $K apply -f - >/dev/null
    $K -n sre-system create configmap oidc-ca --from-file=ca.crt=remote-pki/ca.crt --dry-run=client -o yaml | $K apply -f - >/dev/null
    sed -e "s|__ISSUER_BASE__|$issuer_base|g" -e "s|__ISSUER__|$issuer|g" remote-mcp.yaml | $K apply -f -
    $K -n keycloak rollout restart deploy/keycloak >/dev/null   # pick up cert changes
    $K -n keycloak rollout status deploy/keycloak --timeout=300s
    $K -n sre-system rollout restart deploy/kubernetes-mcp-server >/dev/null   # pick up config changes
    $K -n sre-system rollout status deploy/kubernetes-mcp-server --timeout=120s
    secret() { $K -n keycloak get secret clients -o jsonpath="{.data.$1}" | base64 -d; }
    (umask 077; cat > remote.env <<EOF
# Generated by lab.sh remote-up. Agent side of the remote MCP server (needs lab.sh remote-forward running).
SRE_MCP_URL=http://localhost:18081/mcp
SRE_OIDC_TOKEN_URL=https://localhost:18080/realms/sre/protocol/openid-connect/token
SRE_OIDC_CA=$LAB/remote-pki/ca.crt
SRE_OIDC_CLIENT_ID=sre-agent
SRE_OIDC_CLIENT_SECRET=$(secret sre-agent)
# Negative test only: a valid client in the same realm whose tokens lack the MCP audience
SRE_TEST_OTHER_CLIENT_SECRET=$(secret other-app)
EOF
)
    echo "Remote MCP ready. Next: lab/lab.sh remote-forward (keep it running), then mise run agent:remote"
    ;;
  remote-forward)
    trap 'kill 0' EXIT
    $K -n keycloak port-forward svc/keycloak 18080:8443 &
    $K -n sre-system port-forward svc/kubernetes-mcp-server 18081:8080 &
    wait
    ;;
  remote-down)
    sed 's|__ISSUER[A-Z_]*__|x|g' remote-mcp.yaml | $K delete -f - --ignore-not-found
    $K -n sre-system delete configmap oidc-ca --ignore-not-found
    rm -rf remote.env remote-pki   # the API server keeps trusting the (now absent) issuer until lab.sh down
    ;;
  *)
    sed -n '2,8p' "$0"; echo; scenarios; exit 1 ;;
esac
