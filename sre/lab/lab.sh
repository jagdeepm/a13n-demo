#!/usr/bin/env bash
# Local kind lab for the SRE agent.
#   lab.sh up                 create cluster, metrics-server, shop app, read-only identity + MCP config
#   lab.sh break <scenario>   inject a failure (see list below)
#   lab.sh reset              restore the healthy baseline
#   lab.sh status             what's running
#   lab.sh down               delete the cluster
set -euo pipefail
cd "$(dirname "$0")"
LAB=$(pwd)
CLUSTER=sre-lab
CTX=kind-$CLUSTER
K="kubectl --context $CTX"
METRICS_SERVER=v0.9.1

scenarios() {
  cat <<'EOF'
  crashloop     checkout-api rollout with a bad flag -> new pod CrashLoopBackOff, rollout stuck (old pods still serve)
  bad-image     checkout-api image tag typo -> new pod ErrImagePull/ImagePullBackOff, rollout stuck
  oom           payments-worker loads 128MB under a 64Mi limit -> new pod OOMKilled, restarting
  pending       frontend requests 32 CPUs -> new pod Pending (Insufficient cpu), rollout stuck
  no-endpoints  checkout-api Service selector typo -> pods healthy, but traffic fails (loadgen 000s)
  errors        checkout-api random errors -> pods healthy, ~1/3 requests fail (loadgen 4xx/5xx)
  unready       frontend readiness never passes -> new pod Running 0/1 Ready, rollout stuck
EOF
}

add_arg() {  # deployment arg
  $K -n shop patch deploy "$1" --type=json -p "[{\"op\":\"add\",\"path\":\"/spec/template/spec/containers/0/args/-\",\"value\":\"$2\"}]"
}

case "${1:-}" in
  up)
    kind get clusters | grep -qx $CLUSTER || kind create cluster --name $CLUSTER --wait 120s
    $K apply -f "https://github.com/kubernetes-sigs/metrics-server/releases/download/$METRICS_SERVER/components.yaml"
    # kind kubelets use self-signed certs
    $K -n kube-system patch deploy metrics-server --type=json \
      -p '[{"op":"add","path":"/spec/template/spec/containers/0/args/-","value":"--kubelet-insecure-tls"}]' || true
    $K apply -f rbac.yaml
    # first apply creates the CRD; its SLO objects need it Established, so wait and apply again
    $K apply -f app.yaml || { $K wait --for condition=established --timeout=60s crd/servicelevelobjectives.sre.demo.io; $K apply -f app.yaml; }
    $K -n shop rollout status deploy --timeout=180s

    # Read-only kubeconfig for the MCP server (token valid 24h; re-run `lab.sh up` to refresh).
    server=$(kubectl config view --raw -o jsonpath="{.clusters[?(@.name==\"$CTX\")].cluster.server}")
    kubectl config view --raw -o jsonpath="{.clusters[?(@.name==\"$CTX\")].cluster.certificate-authority-data}" | base64 -d > ca.crt
    token=$($K -n sre-system create token sre-agent --duration=24h)
    rm -f readonly.kubeconfig
    KC="kubectl --kubeconfig readonly.kubeconfig"
    $KC config set-cluster $CLUSTER --server="$server" --certificate-authority=ca.crt --embed-certs=true >/dev/null
    $KC config set-credentials sre-agent --token="$token" >/dev/null
    $KC config set-context sre-agent --cluster=$CLUSTER --user=sre-agent --namespace=shop >/dev/null
    $KC config use-context sre-agent >/dev/null
    rm -f ca.crt; chmod 600 readonly.kubeconfig

    cat > mcp.toml <<EOF
# containers/kubernetes-mcp-server config (generated by lab.sh up)
kubeconfig = "$LAB/readonly.kubeconfig"
read_only = true              # only tools annotated readOnlyHint=true are registered
toolsets = ["core"]           # pods, generic resources (incl. CRDs), events, nodes, top
denied_resources = [{group = "", version = "v1", kind = "Secret"}]
log_file = "$LAB/mcp.log"
EOF
    echo; echo "Lab ready. Read-only identity check:"
    $KC auth can-i delete pods -n shop || true
    $KC auth can-i list servicelevelobjectives.sre.demo.io -n shop
    echo; echo "Scenarios:"; scenarios
    ;;
  break)
    case "${2:-}" in
      crashloop)    add_arg checkout-api --port=nine-eight-nine-eight ;;
      bad-image)    $K -n shop set image deploy/checkout-api app=ghcr.io/stefanprodan/podinfo:6.17.0-hotfix ;;
      oom)          add_arg payments-worker --stress-memory=128 ;;
      pending)      $K -n shop set resources deploy/frontend --requests=cpu=32 ;;
      no-endpoints) $K -n shop patch svc checkout-api -p '{"spec":{"selector":{"app":"checkout"}}}' ;;
      errors)       add_arg checkout-api --random-error ;;
      unready)      add_arg frontend --unready ;;
      *) echo "usage: lab.sh break <scenario>"; scenarios; exit 1 ;;
    esac
    echo "Injected '$2'. Give it ~30s to show symptoms, then ask the agent e.g. 'customers report checkout problems, investigate the shop namespace'."
    ;;
  reset)
    $K apply -f app.yaml >/dev/null
    $K -n shop rollout status deploy --timeout=180s
    ;;
  status)
    $K -n shop get deploy,pods,svc,endpointslices,slo -o wide
    ;;
  down)
    kind delete cluster --name $CLUSTER
    rm -f readonly.kubeconfig mcp.toml mcp.log
    ;;
  *)
    sed -n '2,8p' "$0"; echo; scenarios; exit 1 ;;
esac
